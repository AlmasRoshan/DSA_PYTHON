# Find the largest & smallest ele in an arr

def largest_smallest_ele(nums):
    largest = max(nums)
    print("largest ele:", largest)
    smallest = min(nums)
    print("smallest ele:", smallest)
largest_smallest_ele([10, 20, 30])

